import { describe, expect, it } from 'vitest';
import {
  parseGlobalsFile,
  parseProjectFile,
  parseScreenFile,
} from '../../src/core/parser/index.js';
import {
  checkProject,
  formatHeaderStamp,
  generate,
  GENERATED_MARKER,
  isGeneratedContent,
  type ProjectModel,
} from '../../src/core/generator/index.js';
import { DIAGNOSTIC_CODES, type Diagnostic } from '../../src/core/schema/diagnostic.js';
import { CATALOGUE } from '../../src/data/catalogue.js';
import { frameworkRegistry } from '../helpers/manifest-registry.js';

const PROJECT_XML = `<u8g2gl schema="0.4" name="gen" version="1.0.0">
    <targets>
        <target name="primary" setup="U8G2_SSD1306_128X64_NONAME_F_HW_I2C" />
        <target name="secondary" setup="U8G2_SSD1306_128X64_NONAME_F_HW_I2C" />
    </targets>
</u8g2gl>
`;

const BUILTIN_GLOBALS_XML = `<globals><fonts><builtin name="u8g2_font_6x10_mr" /></fonts></globals>
`;

const BDF_GLOBALS_XML = `<globals><fonts><bdf name="u8g2_font_6x10_mr" src="fonts/f.bdf" /></fonts></globals>
`;

function screenXml(screen: string, label: string | undefined): string {
  const name = label === undefined ? '' : ` name="${label}"`;
  return `<screen name="${screen}">
    <view>
        <u8g2gl_label${name} x="0" y="0" width="128" height="12" font="u8g2_font_6x10_mr" text="Hi" />
    </view>
</screen>
`;
}

/** A two-screen project model, as the loader would build it. */
function model(options: { globals?: string; unnamed?: boolean } = {}): ProjectModel {
  const loadDiagnostics: Diagnostic[] = [];
  const home = parseScreenFile(screenXml('home', options.unnamed ? undefined : 'home_title'), 'screens/screen_home.xml');
  const settings = parseScreenFile(screenXml('settings', 'settings_title'), 'screens/screen_settings.xml');
  loadDiagnostics.push(...home.diagnostics, ...settings.diagnostics);
  return {
    project: parseProjectFile(PROJECT_XML, 'u8g2gl.xml').value!,
    globals: parseGlobalsFile(options.globals ?? BUILTIN_GLOBALS_XML, 'globals.xml').value!,
    screens: [home.value, settings.value].filter((s) => s !== undefined),
    manifests: frameworkRegistry(),
    catalogue: CATALOGUE,
    loadDiagnostics,
    hasProjectManifest: true,
  };
}

describe('generate() (PR-04 WO5b)', () => {
  it('lays out the §13.7 file set in a fixed order, each file a header stamp', () => {
    const result = generate({ ...model(), generatorVersion: '9.9.9' });

    expect(result.errors).toBe(0);
    expect(result.target).toBe('primary');
    expect(result.files.map((f) => f.path)).toEqual([
      'u8g2gl_generated_config.h',
      'ui.hpp',
      'ui_subjects.cpp',
      'ui_styles.cpp',
      'ui_fonts.cpp',
      'ui_images.cpp',
      'ui.cpp',
      'ui_screen_home.cpp',
      'ui_screen_settings.cpp',
    ]);
    // The stamp is still pinned exactly, but WO9 emits content after it, so the
    // assertion is on the opening rather than on the whole file.
    const stamp =
      "// GENERATED by u8g2gl. Do not edit: regenerate with 'u8g2gl generate'.\n" +
      '// source: u8g2gl.xml\n' +
      '// schema: 0.4\n' +
      '// generator: 9.9.9\n' +
      '// target: primary\n';
    expect(result.files.find((f) => f.path === 'ui.hpp')?.content.startsWith(stamp)).toBe(true);
    expect(result.files.find((f) => f.path === 'ui_fonts.cpp')?.content).toContain('// source: globals.xml\n');
    expect(result.files.find((f) => f.path === 'ui_screen_settings.cpp')?.content).toContain(
      '// source: screens/screen_settings.xml\n',
    );
    expect(result.files.every((f) => isGeneratedContent(f.content))).toBe(true);
  });

  it('stamps no timestamp and no absolute path', () => {
    const { files } = generate({ ...model(), generatorVersion: '9.9.9' });
    for (const file of files) {
      expect(file.content).not.toMatch(/\d{4}-\d{2}-\d{2}|\d{1,2}:\d{2}/);
      expect(file.content).not.toMatch(/source: \//);
    }
  });

  it('is byte-identical across runs', () => {
    const first = generate({ ...model(), generatorVersion: '1.0.0' });
    const second = generate({ ...model(), generatorVersion: '1.0.0' });

    expect(JSON.stringify(second)).toBe(JSON.stringify(first));
  });

  it('builds the named target, and suggests the nearest for an unknown one', () => {
    const secondary = generate({ ...model(), target: 'secondary', generatorVersion: '1.0.0' });
    expect(secondary.target).toBe('secondary');
    expect(secondary.files[0]?.content).toContain('// target: secondary\n');

    const unknown = generate({ ...model(), target: 'primry', generatorVersion: '1.0.0' });
    const diagnostic = unknown.diagnostics.find((d) => d.code === DIAGNOSTIC_CODES.UNKNOWN_TARGET);
    expect(unknown.files).toEqual([]);
    expect(unknown.errors).toBe(1);
    expect(diagnostic?.suggestions).toEqual(['primary']);
    expect(diagnostic?.file).toBe('u8g2gl.xml');
  });

  it('refuses a not-yet-supported construct that validate only warns about — same code and location', () => {
    const input = model({ globals: BDF_GLOBALS_XML });
    const validated = checkProject(input, 'warning');
    const generated = generate({ ...input, generatorVersion: '1.0.0' });

    const warned = validated.diagnostics.filter((d) => d.code === DIAGNOSTIC_CODES.NOT_YET_SUPPORTED);
    const refused = generated.diagnostics.filter((d) => d.code === DIAGNOSTIC_CODES.NOT_YET_SUPPORTED);

    expect(validated.errors).toBe(0);
    expect(warned).toHaveLength(1);
    expect(warned[0]?.severity).toBe('warning');
    expect(generated.files).toEqual([]);
    expect(refused).toEqual(warned.map((d) => ({ ...d, severity: 'error' })));
  });

  it('refuses a missing name with the diagnostic validate reports — never inventing one', () => {
    const input = model({ unnamed: true });
    const validated = checkProject(input, 'warning');
    const generated = generate({ ...input, generatorVersion: '1.0.0' });

    const missing = (ds: readonly Diagnostic[]): Diagnostic[] =>
      ds.filter((d) => d.code === DIAGNOSTIC_CODES.MISSING_NAME);
    expect(missing(validated.diagnostics)).toHaveLength(1);
    expect(missing(generated.diagnostics)).toEqual(missing(validated.diagnostics));
    expect(missing(generated.diagnostics)[0]?.severity).toBe('error');
    expect(generated.files).toEqual([]);
  });

  it('marker and stamp agree: a stamp always begins with the marker', () => {
    const stamp = formatHeaderStamp({ source: 'u8g2gl.xml', schema: '0.4', generator: '1', target: 't' });
    expect(stamp.startsWith(`${GENERATED_MARKER}\n`)).toBe(true);
    expect(isGeneratedContent(`// hand-written\n${stamp}`)).toBe(false);
  });
});

describe('checkProject() single-file schema (PR-04 WO5a finding 6)', () => {
  const screenOnly = (): ProjectModel => ({
    ...model(),
    project: { schema: '', name: 'unnamed', version: '1.0.0', targets: [] },
    globals: parseGlobalsFile(BUILTIN_GLOBALS_XML, 'globals.xml').value!,
    hasProjectManifest: false,
  });

  it('does not report a schema version for a lone file that declares none', () => {
    const codes = checkProject(screenOnly(), 'warning').diagnostics.map((d) => d.code);
    expect(codes).not.toContain(DIAGNOSTIC_CODES.UNKNOWN_SCHEMA_VERSION);
  });

  it('still reports it when a project manifest was loaded', () => {
    const codes = checkProject({ ...screenOnly(), hasProjectManifest: true }, 'warning').diagnostics.map(
      (d) => d.code,
    );
    expect(codes).toContain(DIAGNOSTIC_CODES.UNKNOWN_SCHEMA_VERSION);
  });

  it('generate refuses a lone file, naming the project it needs', () => {
    const result = generate({ ...screenOnly(), generatorVersion: '1.0.0' });
    expect(result.files).toEqual([]);
    expect(result.diagnostics.map((d) => d.code)).toEqual([DIAGNOSTIC_CODES.MISSING_FILE]);
  });
});
